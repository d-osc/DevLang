'use strict';
// Exercise rendering/filtering with hostile metadata; fixtures never enter the deployed catalog.
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const nodes={};
const node=id => nodes[id] ||= {innerHTML:'',textContent:'',value:''};
const escapeHTML=value => String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const sandbox={document:{getElementById:node,addEventListener(){}},location:{hash:'#/packages'},escapeHTML,encodeURIComponent,decodeURIComponent,Date,prepareCode(){},codeBlock:code=>'<pre>'+escapeHTML(code)+'</pre>'};
vm.createContext(sandbox);vm.runInContext(fs.readFileSync('website/src/packages.js','utf8'),sandbox);
const fixture={id:'owner/math',name:'math',owner:'owner',description:'<img src=x onerror=alert(1)>',repository:'https://github.com/owner/math',topics:['devlang-package'],stars:4,bin:{},license:'MIT',updated_at:'2026-10-11',checked_commit:'a'.repeat(40),source_version:'1.0.0',modules:'src',dependencies:[],peers:{},versions:[{version:'1.0.0',tag:'v1.0.0',commit:'a'.repeat(40)}],latest:{version:'1.0.0',tag:'v1.0.0',commit:'a'.repeat(40)}};
sandbox.fixture=fixture;
vm.runInContext("packageCatalog={schema_version:1,generated_at:'2026-10-11',packages:[fixture,{...fixture,id:'another/cli',name:'tool',bin:{mycli:'src/cli.dev'},stars:10}]};paintPackages()",sandbox);
assert.equal(node('package-count').textContent,'2 / 2 packages');
assert.ok(node('package-results').innerHTML.includes('&lt;img'));
assert.ok(!node('package-results').innerHTML.includes('<img'));
vm.runInContext("packageState.kind='cli';filterPackages()",sandbox);
assert.equal(node('package-count').textContent,'1 / 2 packages');
assert.ok(node('package-results').innerHTML.includes('another/cli') && !node('package-results').innerHTML.includes('owner/math'));
vm.runInContext("packageState.kind='all';packageState.query='OWNER';filterPackages()",sandbox);
assert.equal(node('package-count').textContent,'1 / 2 packages');
sandbox.location.hash='#/packages/owner/math';vm.runInContext('paintPackages()',sandbox);
assert.ok(node('package-view').innerHTML.includes('d pkg add math --git https://github.com/owner/math.git --tag v1.0.0'));
assert.ok(node('package-view').innerHTML.includes('&lt;img') && !node('package-view').innerHTML.includes('<img'));
vm.runInContext('fixture.latest=null;paintPackages()',sandbox);
assert.ok(!node('package-view').innerHTML.includes('d pkg add'));
sandbox.location.hash='#/packages/%ZZ';vm.runInContext('paintPackages()',sandbox);
assert.ok(node('package-view').innerHTML.includes('ไม่พบ package นี้'));
vm.runInContext('packageError=true;paintPackages()',sandbox);
assert.ok(node('package-view').innerHTML.includes('data-package-refresh'));
console.log('Package Store UI: filtering, ownership, escaping, install tags, source-only, invalid routes and retry passed');
